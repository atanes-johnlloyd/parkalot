    private void refreshSettings() {
        try {
            valuelot.setText(settingsController.getLotName());
            locvalue.setText(settingsController.getLocation());
            valuecur.setText(settingsController.getCurrency());
            valuetime.setText(settingsController.getTimeZone());
            valueends.setText(settingsController.getWeekendRate());
            valuedays.setText(settingsController.getWeekdayRate());
            valuestay.setText(settingsController.getMaxStay());
            valueover.setText(settingsController.getOverstayPenalty());
            valueadv.setText(settingsController.getMaxAdvance());
            valuereserv.setText(settingsController.getMaxReservationSlot());
            valuegrace.setText(settingsController.getGracePeriod());

            if (settingsController.getAllowPrintTicket().equals("yes")) {
                rdreservation.setSelected(true);
            } else {
                rdreservation.setSelected(false);
            }

            valuecancelation.setText(settingsController.getCancellationWindow());

            // Fix: use radio button instead of text field
            rdNotifyMissed.setSelected(
                settingsController.getNotifyOnMissed().equals("yes"));

        } catch (Exception e) {
            System.out.println("Error loading settings: " + e.getMessage());
        }
    }
    
    // Add this event for the Lot Name text field
