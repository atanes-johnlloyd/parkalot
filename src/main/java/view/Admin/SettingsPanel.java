    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
        settingsController.setLotName(valuelot.getText().trim());
        settingsController.setLocation(locvalue.getText().trim());
        settingsController.setCurrency(valuecur.getText().trim());
        settingsController.setTimeZone(valuetime.getText().trim());
        settingsController.setWeekendRate(valueends.getText().trim());
        settingsController.setWeekdayRate(valuedays.getText().trim());
        settingsController.setMaxStay(valuestay.getText().trim());
        settingsController.setOverstayPenalty(valueover.getText().trim());
        settingsController.setMaxAdvance(valueadv.getText().trim());
        settingsController.setMaxReservationSlot(valuereserv.getText().trim());
        settingsController.setGracePeriod(valuegrace.getText().trim());

        if (rdreservation.isSelected()) {
            settingsController.setAllowPrintTicket("yes");
        } else {
            settingsController.setAllowPrintTicket("no");
        }

        settingsController.setCancellationWindow(valuecancelation.getText().trim());

        // Fix: use radio button
        if (rdNotifyMissed.isSelected()) {
            settingsController.setNotifyOnMissed("yes");
        } else {
            settingsController.setNotifyOnMissed("no");
        }

        JOptionPane.showMessageDialog(this, "Settings saved!");
    }//GEN-LAST:event_btnsaveActionPerformed

