    private void btnConfirmActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmActionPerformed
        try {
            double received = Double.parseDouble(txtReceived.getText().trim());

            if (received < amount) {
                Dialogue_SystemMessage.showMessage((java.awt.Frame) getParent(),
                        "Insufficient payment.");
                return;
            }

            double change = received - amount;
            DecimalFormat df = new DecimalFormat("0.00");

            // Save transaction to DB
            // We need slotNumber, plateNumber, timeIn passed into this dialog
            SlotController slotController = new SlotController();
            slotController.saveTransaction(
                slotNumber,                          // need to pass this in
                plateNumber,                         // need to pass this in
                timeInTimestamp,                     // need to pass this in
                new Timestamp(System.currentTimeMillis()),
                durationMinutes,                     // need to pass this in
                amount,
                received,
                change
            );

            String currency = settingsController.getCurrency();
            Dialogue_SystemMessage.showMessage((java.awt.Frame)getParent(),
                "Payment successful.\nChange: " + currency + df.format(change));

            confirmed = true;
            dispose();

        } catch (NumberFormatException e) {
            Dialogue_SystemMessage.showMessage((java.awt.Frame) getParent(),
                    "Invalid amount received.");
        }
    }//GEN-LAST:event_btnConfirmActionPerformed

