    private void btnConfirmActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmActionPerformed
        String fullName = txtName.getText().trim();
        String newUsername = txtUsername.getText().trim();
        String email = txtEmail.getText().trim();
        String contact = txtContact.getText().trim();
        String position = (String) txtPosition.getSelectedItem();
        position = position.toLowerCase();
        String status = (String) txtStatus.getSelectedItem();
        status = status.toLowerCase();

        // Basic validation
        if(fullName.isEmpty() || newUsername.isEmpty() || email.isEmpty() || contact.isEmpty() || position.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill all fields.");
            return;
        }

        try (Connection conn = model.DBConnection.connect()) {

            // Check if email or username is already taken by someone else
            if(!newUsername.equals(username) && controller.isUsernameRegistered(newUsername)) {
                JOptionPane.showMessageDialog(this, "Username already exists.");
                return;
            }

            if(controller.isEmailRegistered(email) && !email.equalsIgnoreCase(getCurrentEmail())) {
                JOptionPane.showMessageDialog(this, "Email already exists.");
                return;
            }

            String sql = "UPDATE users SET fullname=?, username=?, email=?, contact=?, role=?, status=? WHERE username=?";
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, fullName);
            pst.setString(2, newUsername);
            pst.setString(3, email);
            pst.setString(4, contact);
            pst.setString(5, position);
            pst.setString(6, status);
            pst.setString(7, username); // original username
            int updated = pst.executeUpdate();
            

            if (updated > 0) {
                String newRole = position; // already lowercased earlier
                boolean demotedSelf = username.equals(model.SessionManager.getUsername())
                    && "staff".equalsIgnoreCase(newRole)
                    && "admin".equalsIgnoreCase(originalRole);

                boolean promoted = "admin".equalsIgnoreCase(newRole)
                    && !"admin".equalsIgnoreCase(originalRole);

                // Send promotion email
                if (promoted) {
                    JOptionPane.showMessageDialog(this,
                        "User updated successfully!\n" +
                        fullName + " has been promoted to Admin.\n" +
                        "A notification email has been sent.");
                } else {
                    JOptionPane.showMessageDialog(this, "User updated successfully!");
                }

                this.dispose();

                // Logout if demoted own account
                if (demotedSelf) {
                    model.SessionManager.logout();
                    new view.LoginForm().setVisible(true);
                    for (java.awt.Window window : java.awt.Window.getWindows()) {
                        if (window instanceof view.Admin.DashboardForm) {
                            window.dispose();
                        }
                    }
                }
            } else {
                JOptionPane.showMessageDialog(this, "Update failed.");
            }

        } catch (SQLException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error updating user.");
        }
    }//GEN-LAST:event_btnConfirmActionPerformed

