    // Load user data into the fields
    private void loadUserData() {
        try (Connection conn = model.DBConnection.connect()) {
            String query = "SELECT fullname, username, email, contact, role, status FROM users WHERE username = ?";
            PreparedStatement pst = conn.prepareStatement(query);
            pst.setString(1, username.trim());
            ResultSet rs = pst.executeQuery();
            
            if (rs.next()) {
                txtName.setText(rs.getString("fullname"));
                txtUsername.setText(rs.getString("username"));
                txtEmail.setText(rs.getString("email"));
                txtContact.setText(rs.getString("contact"));

                originalRole = rs.getString("role");

                txtPosition.setSelectedItem(controller.capitalize(originalRole));
                txtStatus.setSelectedItem(controller.capitalize(rs.getString("status")));
            }
        } catch (SQLException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Failed to load user data.");
        }
    }
                         

    // Helper to get current email from DB
    private String getCurrentEmail() {
        try (Connection conn = model.DBConnection.connect()) {
            String sql = "SELECT email FROM users WHERE username=?";
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, username);
            ResultSet rs = pst.executeQuery();
            if(rs.next()){
                return rs.getString("email");
            }
        } catch (SQLException e) {
            e.printStackTrace();
        }
        return "";
    }
    
    private void validateRoleChange() {
        String selectedRole = ((String) txtPosition.getSelectedItem()).toLowerCase();

        // Only validate when changing from admin to staff
        if ("admin".equalsIgnoreCase(originalRole) && 
            "staff".equalsIgnoreCase(selectedRole)) {

            AdminUserController adminController = new AdminUserController();
            int adminCount = adminController.getActiveAdminCount();

            // Check if this is the last admin
            if (adminCount <= 1) {
                // Revert — can't remove last admin
                JOptionPane.showMessageDialog(this,
                    "Cannot change role — " + username + 
                    " is the last admin.\nAt least one admin must exist.",
                    "Role Change Blocked",
                    JOptionPane.WARNING_MESSAGE
                );
                // Revert combobox back to Admin
                txtPosition.removeActionListener(txtPosition.getActionListeners()[0]);
                txtPosition.setSelectedItem("Admin");
                txtPosition.addActionListener(e -> validateRoleChange());
                return;
            }

            // Warn if demoting own account
            if (username.equals(model.SessionManager.getUsername())) {
                int confirm = JOptionPane.showConfirmDialog(this,
                    "You are changing your own role to Staff.\n" +
                    "You will be logged out after saving.\nContinue?",
                    "Warning",
                    JOptionPane.YES_NO_OPTION,
                    JOptionPane.WARNING_MESSAGE
                );

                if (confirm != JOptionPane.YES_OPTION) {
                    // Revert
                    txtPosition.removeActionListener(txtPosition.getActionListeners()[0]);
                    txtPosition.setSelectedItem("Admin");
                    txtPosition.addActionListener(e -> validateRoleChange());
                }
            }
        }
    }
