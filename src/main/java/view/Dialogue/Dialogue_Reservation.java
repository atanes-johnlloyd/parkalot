    private void btnConfirmActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmActionPerformed
        String plateNo = txtPlateNo.getText().trim().toUpperCase();
        String slotText = txtSlotNo.getText().trim();
        String contactText = txtContactNo.getText().trim();
        
        if (plateNo.equals("E.G. ABC123")) plateNo = "";
        if (slotText.equals("e.g. 5")) slotText = "";
        if (contactText.equals("e.g. 09123456789")) contactText = "";
        
        if (plateNo.isEmpty() || slotText.isEmpty() || contactText.isEmpty()) {
            Dialogue_SystemMessage.showMessage(parent, "Please fill all fields!");
            return;
        }
        
        if (!plateNo.matches("[A-Z0-9-]+")) {
            Dialogue_SystemMessage.showMessage(parent, "Plate number should contain only letters, numbers, and hyphens.");
            txtPlateNo.requestFocus();
            return;
        }

        int slotNo;
        try {
            slotNo = Integer.parseInt(slotText);
            if (slotNo < 1 || slotNo > 999) {
                Dialogue_SystemMessage.showMessage(parent, "Slot number must be between 1 and 999.");
                return;
            }
        } catch (NumberFormatException e) {
            Dialogue_SystemMessage.showMessage(parent, "Slot number must be a valid number.");
            return;
        }

        try {
            long contact = Long.parseLong(contactText);
            if (contactText.length() < 10 || contactText.length() > 15) {
                Dialogue_SystemMessage.showMessage(parent, "Contact number must be between 10 and 15 digits.");
                txtContactNo.requestFocus();
                return;
            }
        } catch (NumberFormatException e) {
            Dialogue_SystemMessage.showMessage(parent, "Contact number must contain numbers only.");
            txtContactNo.requestFocus();
            return;
        }

        // ===== MAX ADVANCE VALIDATION =====
        int maxAdvanceDays;
        try {
            maxAdvanceDays = Integer.parseInt(settingsController.getMaxAdvance());
        } catch (NumberFormatException e) {
            maxAdvanceDays = 7; // Default value
            System.out.println("Warning: Using default max advance days");
        }
        // ===== END MAX ADVANCE VALIDATION =====

        try {
            // ===== PLATE NUMBER VALIDATIONS =====
            boolean hasActiveReservation = slotController.hasActiveReservation(plateNo);
            boolean isCurrentlyParked = slotController.isVehicleParked(plateNo);

            if (hasActiveReservation) {
                String reservationDetails = slotController.getActiveReservationDetails(plateNo);
                Dialogue_SystemMessage.showMessage(parent, 
                    "Vehicle with plate number " + plateNo + " already has an active reservation.\n" +
                    reservationDetails);
                txtPlateNo.requestFocus();
                return;
            }

            if (isCurrentlyParked) {
                String parkingDetails = slotController.getParkedVehicleDetails(plateNo);
                Dialogue_SystemMessage.showMessage(parent, 
                    "Vehicle with plate number " + plateNo + " is already parked.\n" +
                    parkingDetails);
                txtPlateNo.requestFocus();
                return;
            }

            // Check max reservation slots per plate
            int maxReservationSlots;
            try {
                maxReservationSlots = Integer.parseInt(settingsController.getMaxReservationSlot());
                int currentReservations = slotController.getActiveReservationCount(plateNo);
                if (currentReservations >= maxReservationSlots) {
                    Dialogue_SystemMessage.showMessage(parent, 
                        "Plate number " + plateNo + " has reached maximum of " + maxReservationSlots + " active reservations.");
                    return;
                }
            } catch (NumberFormatException e) {
                System.out.println("Warning: Could not parse max reservation slots");
            }

            if (!slotController.slotExists(slotNo)) {
                Dialogue_SystemMessage.showMessage(parent, "Slot number does not exist.");
                return;
            }
            
            String status = slotController.getSlotStatus(slotNo);
            if (status.equalsIgnoreCase("reserved") || status.equalsIgnoreCase("occupied")) {
                Dialogue_SystemMessage.showMessage(parent, "Slot is already taken.");
                return;
            }

            String vehicleType;
            try {
                vehicleType = slotController.getSlotVehicle(slotNo);
            } catch (SQLException e) {
                Dialogue_SystemMessage.showMessage(parent, "Failed to get vehicle type for slot " + slotNo);
                return;
            }

            Date selectedDate = (Date) jSpinner1.getValue();
            Timestamp reservationTime = new Timestamp(selectedDate.getTime());
            Timestamp now = new Timestamp(System.currentTimeMillis());

            if (reservationTime.before(now)) {
                Dialogue_SystemMessage.showMessage(parent, "Reservation time cannot be in the past.");
                return;
            }
            
            // Check max advance days
            long maxAdvanceMillis = (long) maxAdvanceDays * 24 * 60 * 60 * 1000;
            if (reservationTime.getTime() > now.getTime() + maxAdvanceMillis) {
                Dialogue_SystemMessage.showMessage(parent, 
                    "Reservation cannot be made more than " + maxAdvanceDays + " days in advance.");
                return;
            }

            // Check for time conflicts
            boolean isSlotAvailable = slotController.isSlotAvailableAtTime(slotNo, reservationTime);
            if (!isSlotAvailable) {
                String conflictDetails = slotController.getConflictingReservationDetails(slotNo, reservationTime);
                Dialogue_SystemMessage.showMessage(parent, 
                    "Slot " + slotNo + " is already reserved at that time.\n" +
                    conflictDetails);
                return;
            }

            // Check grace period
            int gracePeriod = Integer.parseInt(settingsController.getGracePeriod());
            boolean hasGracePeriodConflict = slotController.hasGracePeriodConflict(slotNo, reservationTime, gracePeriod);
            if (hasGracePeriodConflict) {
                Dialogue_SystemMessage.showMessage(parent, 
                    "Cannot reserve within " + gracePeriod + " minutes of an existing reservation.");
                return;
            }

            slotController.reserveSlot(slotNo, plateNo, contactText, vehicleType, reservationTime);

            Dialogue_SystemMessage.showMessage(parent, "Slot " + slotNo + " reserved successfully!");

            if (reservationPanel != null) {
                reservationPanel.loadReservations();
            }
            if (parent instanceof HomeForm) {
                HomeForm home = (HomeForm) parent;
                SwingUtilities.invokeLater(() -> home.loadSlotsFromDatabase());
            }

            txtPlateNo.setText("");
            txtSlotNo.setText("");
            txtContactNo.setText("");

            dispose();

        } catch (SQLException e) {
            e.printStackTrace();
            logger.severe("SQL Error: " + e.getMessage());
            if (e.getMessage() != null && e.getMessage().contains("already reserved")) {
                Dialogue_SystemMessage.showMessage(parent, 
                    "Slot is already reserved. Please check availability and try again.");
            } else {
                Dialogue_SystemMessage.showMessage(parent, "Database error occurred: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnConfirmActionPerformed

