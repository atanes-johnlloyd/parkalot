    private void txtSlotNoFocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_txtSlotNoFocusLost
        String slotText = txtSlotNo.getText().trim();
        if (slotText.isEmpty()) return;

        int slotNo;
        try {
            slotNo = Integer.parseInt(slotText);
        } catch (NumberFormatException e) {

            Dialogue_SystemMessage.showMessage(parent, "Slot number must be numeric.");
            txtSlotNo.setText("");
            return;
        }

        try {
            // Check if slot exists
            if (!slotController.slotExists(slotNo)) {
                Dialogue_SystemMessage.showMessage(parent, "Slot number does not exist.");
                return;
            }

            String vehicleType = slotController.getSlotVehicle(slotNo);

            if (vehicleType != null) {
                isAutoUpdating = true; // 🔒 prevent combo listener

                switch (vehicleType.toLowerCase()) {
                    case "car":
                        jComboBox1.setSelectedItem("Car");
                        break;
                    case "motor":
                        jComboBox1.setSelectedItem("Motor");
                        break;
                    case "pwd":
                        jComboBox1.setSelectedItem("PWD");
                        break;
                }

                isAutoUpdating = false; // 🔓 allow again
            }

        } catch (SQLException ex) {
            ex.printStackTrace();
            Dialogue_SystemMessage.showMessage(parent, "Database error occurred!");
            txtSlotNo.setText("");
        }
    }//GEN-LAST:event_txtSlotNoFocusLost

