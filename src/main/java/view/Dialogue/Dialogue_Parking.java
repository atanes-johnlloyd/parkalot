    private void btnConfirmActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmActionPerformed
        String plateNo = txtPlateNo.getText().trim().toUpperCase();
        String contactText = txtContact.getText().trim();
        
        if (plateNo.equals("E.G. ABC123")) plateNo = "";
        if (contactText.equals("e.g. 09123456789 (Optional)")) contactText = "";
        
        if (plateNo.isEmpty()) {
            Dialogue_SystemMessage.showMessage(parent, "Please enter a plate number.");
            return;
        }
        
        try {
            long contact = Long.parseLong(contactText);
        } catch (NumberFormatException e) {
            Dialogue_SystemMessage.showMessage(parent, "Contact number must contain numbers only.");
            txtContact.requestFocus();
            return;
        }
        
        if (!contactText.isEmpty()) {
            if (!contactText.matches("\\d+")) {
                Dialogue_SystemMessage.showMessage(parent, 
                    "Contact number must contain numbers only.");
                txtContact.requestFocus();
                return;
            }
            if (contactText.length() < 10 || contactText.length() > 15) {
                Dialogue_SystemMessage.showMessage(parent,
                    "Contact number must be between 10 and 15 digits.");
                txtContact.requestFocus();
                return;
            }
        }

        SlotController controller = new SlotController();
        
        if (controller.isPlateParked(plateNo)) {
            Dialogue_SystemMessage.showMessage(parent, "Plate " + plateNo + " is already parked!");
            return;
        }

        // Check if the plate has a reserved slot
        if (controller.isPlateReserved(plateNo)) {
            Dialogue_SystemMessage.showMessage(parent, "Plate " + plateNo + " already has a reserved slot!");
            return;
        }

        boolean success = controller.parkVehicle(slot, plateNo, contactText);

        if (success) {
            TicketInfo info = controller.getTicketInfo(slot);
            if (info != null) {
                controller.SettingsController settings = 
                    new controller.SettingsController();

                if (settings.isPrintTicketEnabled()) {
                    String date = "________", time = "________";
                    if (info.timeIn != null) {
                        java.text.SimpleDateFormat dateFormat = 
                            new java.text.SimpleDateFormat("yyyy-MM-dd");
                        java.text.SimpleDateFormat timeFormat = 
                            new java.text.SimpleDateFormat("hh:mm a");
                        date = dateFormat.format(info.timeIn);
                        time = timeFormat.format(info.timeIn);
                    }

                    Dialogue_Ticket dialog = new Dialogue_Ticket(parent, true);
                    dialog.setTicketInfo(
                        String.valueOf(info.slotNo),
                        date,
                        time,
                        info.plate,
                        info.vehicleType,
                        String.valueOf(info.slotNo),
                        "________",
                        "________"
                    );
                    dialog.setAlwaysOnTop(true);
                    dialog.setVisible(true);
                } else {
                    // No ticket — just show confirmation
                    Dialogue_SystemMessage.showMessage(parent,
                        "Vehicle " + info.plate + 
                        " parked at slot " + info.slotNo + ".");
                }
                dispose();
            }
        } else {
            Dialogue_SystemMessage.showMessage(parent, "Parking failed.");
        }
    }//GEN-LAST:event_btnConfirmActionPerformed

